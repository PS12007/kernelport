"""Device-only view of a real-world CUDA file, for NVRTC.

Real .cu files mix kernels with host code: CPU reference functions, main(),
cudaMalloc, <<<...>>> launches, cuBLAS handles, <stdio.h>. NVRTC compiles device
code only and has no host headers, so compiling such a file as-is fails.

``device_source`` walks the file's top level and keeps what device code can need:

- ``__global__`` / ``__device__`` functions (also via macros such as
  ``#define DEVICE __device__ __forceinline__``)
- types (struct/class/union/enum), typedefs, ``using``, templates of those
- ``__device__`` / ``__constant__`` / const / constexpr variables
- preprocessor directives, except host-only ``#include <...>`` headers
- local ``#include "x.h"`` files, inlined (once each) with ``#line`` markers

and blanks out host functions, host prototypes and host globals. Blanked text is
replaced by spaces with every newline kept, so NVRTC's line numbers still point at
the user's file. The original file is what gets hashed and frozen; this view is
only what NVRTC compiles.

This is lexical, not a C++ front end: kernels generated by macros, or a top-level
macro call with no trailing ``;`` followed by a kernel, can confuse it.
"""

from __future__ import annotations

import re
from pathlib import Path

from kernelport.analyzer.cuda_parser import strip_comments_and_strings

# Headers NVRTC (or hipRTC) can provide; every other <...> include is host-only.
DEVICE_HEADER_PREFIXES = ("cuda_fp16", "cuda_bf16", "cuda_fp8", "cuda_fp4", "cuda_fp6", "cooperative_groups",
                          "mma.h", "cuda/", "cub/", "curand_kernel", "curand_philox", "cuda_pipeline",
                          "cuda_awbarrier", "sm_", "crt/", "hip/", "vector_types.h", "vector_functions.h")

_CUDA_HOST_HEADERS = ("cuda_runtime", "cuda.h", "cublas", "cudnn", "cusparse", "curand.h", "cufft", "nccl",
                      "cusolver", "nvToolsExt", "nvtx")

# Constants host headers would have supplied (math.h, float.h, limits.h).
SHIM = """#ifndef M_PI
#define M_PI 3.14159265358979323846
#endif
#ifndef M_SQRT2
#define M_SQRT2 1.41421356237309504880
#endif
#ifndef M_SQRT1_2
#define M_SQRT1_2 0.70710678118654752440
#endif
#ifndef M_E
#define M_E 2.7182818284590452354
#endif
#ifndef M_LN2
#define M_LN2 0.69314718055994530942
#endif
#ifndef FLT_MAX
#define FLT_MAX 3.402823466e+38F
#endif
#ifndef FLT_MIN
#define FLT_MIN 1.175494351e-38F
#endif
#ifndef FLT_EPSILON
#define FLT_EPSILON 1.192092896e-07F
#endif
#ifndef DBL_MAX
#define DBL_MAX 1.7976931348623158e+308
#endif
#ifndef INT_MAX
#define INT_MAX 2147483647
#endif
#ifndef INT_MIN
#define INT_MIN (-2147483647 - 1)
#endif
#ifndef UINT_MAX
#define UINT_MAX 0xffffffffU
#endif
"""

_DEVICE_WORDS = {"__global__", "__device__"}
_KEEP_DECL_WORDS = {"__device__", "__constant__", "__shared__", "__managed__", "constexpr", "static_assert",
                    "typedef", "using", "const", "struct", "class", "union", "enum", "template"}
_TYPE_WORDS = {"struct", "class", "union", "enum"}
_INCLUDE = re.compile(r'#\s*include\s*([<"])([^>"]+)[>"]')
_OBJECT_MACRO = re.compile(r"^[ \t]*#[ \t]*define[ \t]+(\w+)[ \t]+(.*)$", re.M)


def _strip_templates(s: str) -> str:
    """Remove <...> template argument lists (innermost first)."""
    prev = None
    while prev != s:
        prev, s = s, re.sub(r"<[^<>;{}()]*>", "", s)
    return s


def _flatten(header: str) -> str:
    """Header with operator names, comparisons, template args and (...)/[...] groups removed."""
    s = re.sub(r"\boperator\s*[^\w\s(]+", "operator", header)
    s = re.sub(r"[<>!=]=", "", s)
    s = _strip_templates(s)
    prev = None
    while prev != s:
        prev, s = s, re.sub(r"\([^()]*\)|\[[^\[\]]*\]", "", s)
    return s


class SliceError(ValueError):
    """The file could not be sliced (e.g. an include escapes the repo)."""


def _blank(chars: list[str], start: int, end: int) -> None:
    for k in range(start, end):
        if chars[k] != "\n":
            chars[k] = " "


def _device_markers(clean: str) -> set[str]:
    """Words that mark device code: __global__/__device__ and object-like macros expanding to them."""
    marks = set(_DEVICE_WORDS)
    for name, body in _OBJECT_MACRO.findall(clean):
        if set(re.findall(r"\w+", body)) & marks:
            marks.add(name)
    return marks


def _match(clean: str, i: int, open_ch: str, close_ch: str) -> int:
    depth = 0
    for k in range(i, len(clean)):
        if clean[k] == open_ch:
            depth += 1
        elif clean[k] == close_ch:
            depth -= 1
            if depth == 0:
                return k + 1
    return len(clean)


def _directive_end(clean: str, i: int) -> int:
    """End (exclusive, before the newline) of the preprocessor line starting at i, with continuations."""
    while True:
        j = clean.find("\n", i)
        if j < 0:
            return len(clean)
        if clean[:j].rstrip(" \t\r").endswith("\\"):
            i = j + 1
            continue
        return j


def _at_line_start(clean: str, i: int) -> bool:
    k = clean.rfind("\n", 0, i) + 1
    return clean[k:i].strip() == ""


class _Slicer:
    def __init__(self, root: Path | None):
        self.root = root.resolve() if root else None
        self.seen: set[Path] = set()
        self.dropped_cuda_host = False

    def file(self, path: Path) -> str:
        path = path.resolve()
        self.seen.add(path)
        text = path.read_text(encoding="utf-8", errors="replace")
        clean = strip_comments_and_strings(text)
        chars = list(text)
        self.marks = getattr(self, "marks", set()) | _device_markers(clean)  # includes add theirs
        inserts: dict[int, str] = {}
        self._region(text, clean, chars, 0, len(text), path, inserts)
        out, last = [], 0
        for pos in sorted(inserts):
            out.append("".join(chars[last:pos]))
            out.append(inserts[pos])
            last = pos
        out.append("".join(chars[last:]))
        return "".join(out)

    def _region(self, text, clean, chars, i, end, path, inserts) -> None:
        while i < end:
            while i < end and clean[i] in " \t\r\n":
                i += 1
            if i >= end:
                return
            if clean[i] == "#" and _at_line_start(clean, i):
                j = _directive_end(clean, i)
                self._directive(text, clean, chars, i, j, path, inserts)
                i = j
                continue
            if clean[i] == ";":  # stray semicolon
                i += 1
                continue
            j, body = self._item_end(clean, i, end)
            header = clean[i:body[0]] if body else clean[i:j]
            words = set(re.findall(r"\w+", header))
            if body and (header.split()[:1] == ["namespace"] or re.fullmatch(r'\s*extern\s*"\s*"\s*', header)):
                self._region(text, clean, chars, body[0] + 1, body[1] - 1, path, inserts)
            elif body and not self._is_type_or_init(header):
                if not words & self.marks:  # host function definition
                    _blank(chars, i, j)
            elif not body and not self._keep_declaration(header, words):
                _blank(chars, i, j)
            i = j

    def _item_end(self, clean, i, end) -> tuple[int, tuple[int, int] | None]:
        """(end of the item, (body_start, body_end) if it has a top-level { } body)."""
        k = i
        while k < end:
            c = clean[k]
            if c in "([":
                k = _match(clean, k, c, ")" if c == "(" else "]")
                continue
            if c == ";":
                return k + 1, None
            if c == "{":
                b_end = _match(clean, k, "{", "}")
                header = clean[i:k]
                if self._is_type_or_init(header):  # struct S {...}; / int a[] = {...};
                    semi = clean.find(";", b_end, end)
                    return (end if semi < 0 else semi + 1), (k, b_end)
                return b_end, (k, b_end)
            k += 1
        return end, None

    @staticmethod
    def _is_type_or_init(header: str) -> bool:
        """True for `struct S {` / `enum class E : int {` / `T a[] = {` headers; False for functions."""
        h = _flatten(header)
        if "=" in h:
            return True
        return bool(set(re.findall(r"\w+", h)) & _TYPE_WORDS) and not header.rstrip().endswith(")")

    def _keep_declaration(self, header: str, words: set[str]) -> bool:
        if words & self.marks or words & {"__constant__", "__shared__", "__managed__"}:
            return True
        if words & {"typedef", "using", "static_assert"}:
            return True
        if "(" in re.sub(r"=.*", "", _strip_templates(header), flags=re.S):
            return False  # host function prototype, or a host object built by a constructor
        return bool(words & _KEEP_DECL_WORDS)

    def _directive(self, text, clean, chars, i, j, path, inserts) -> None:
        m = _INCLUDE.match(text[i:j].strip())
        if not m:
            return
        kind, name = m.groups()
        if kind == "<":
            if not name.startswith(DEVICE_HEADER_PREFIXES):
                _blank(chars, i, j)
                if name.startswith(_CUDA_HOST_HEADERS):
                    self.dropped_cuda_host = True
            return
        inc = (path.parent / name).resolve()
        if not inc.is_file():
            return  # leave it to the compiler's -I search (and its error message)
        if self.root and self.root not in inc.parents:
            raise SliceError(f"{path.name} includes {name}, which is outside the repo")
        _blank(chars, i, j)
        if inc in self.seen:
            return
        line = text.count("\n", 0, j) + 2
        body = self.file(inc)
        at = j + 1 if j < len(text) else j
        inserts[at] = (("" if at > j else "\n") +
                       f'#line 1 "{inc.name}"\n{body}\n#line {line} "{path.name}"\n')


def device_source(path: Path, root: Path | None = None) -> str:
    """The device-only view of ``path`` (see module docstring), with a small constants shim."""
    slicer = _Slicer(root)
    sliced = slicer.file(Path(path))
    # Under nvcc, cuda_runtime.h / cublas headers pull in the half and bfloat16 types; code
    # that relied on that still needs them.
    fp = "#include <cuda_fp16.h>\n#include <cuda_bf16.h>\n" if slicer.dropped_cuda_host else ""
    return f'{SHIM}{fp}#line 1 "{Path(path).name}"\n{sliced}'
