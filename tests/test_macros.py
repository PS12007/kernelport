"""Kernels defined through macros: the expander, the analyzer, the NVRTC slicer, and a full validation."""

import json
import shutil
from pathlib import Path

from conftest import needs_cuda
from kernelport.analyzer.cuda_parser import scan
from kernelport.analyzer.macros import Expander, find_macros, strip_comments
from kernelport.harness.device_source import device_source

FIX = Path(__file__).parent / "fixtures" / "macro_kernels"


def _expand(defs: str, text: str) -> str:
    return " ".join(Expander(find_macros(strip_comments(defs))).expand(text).split())


def test_paste_stringize_and_variadics():
    defs = ("#define CAT(a, b) a ## b\n#define STR(x) #x\n#define LOG(fmt, ...) printf(fmt, __VA_ARGS__)\n"
            "#define NLOG(fmt, args...) printf(fmt, args)\n")
    assert _expand(defs, "CAT(scale_, f32)") == "scale_f32"
    assert _expand(defs, 'STR(a  +  "b")') == '"a + \\"b\\""'
    assert _expand(defs, 'LOG("%d %d", 1, 2)') == 'printf("%d %d", 1, 2)'
    assert _expand(defs, 'NLOG("%d", 3, 4)') == 'printf("%d", 3, 4)'


def test_nested_and_macro_name_arguments():
    defs = ("#define TWICE(x) ((x) + (x))\n#define FOUR(x) TWICE(TWICE(x))\n"
            "#define DEF(T) T##_t\n#define FOR_TYPES(M) M(float) M(int)\n")
    assert _expand(defs, "FOUR(y)") == "((((y) + (y))) + (((y) + (y))))"
    assert _expand(defs, "FOR_TYPES(DEF)") == "float_t int_t"
    assert _expand(defs + "#define APPLY(F) F\n", "APPLY(DEF)(half) x") == "half_t x"


def test_self_reference_and_missing_args_terminate():
    defs = "#define foo foo + 1\n#define f(x) f(x) * 2\n#define g(x) x\n"
    assert _expand(defs, "foo") == "foo + 1"
    assert _expand(defs, "f(3)") == "f(3) * 2"
    assert _expand(defs, "g") == "g"  # function-like name without arguments is just a name
    assert _expand(defs, "g(") == "g("  # unbalanced: left alone


def test_continuations_and_comments_in_defines():
    defs = "#define K(n) /* comment */ \\\n  __global__ void n() { \\\n  }  // trailing\n"
    macros = find_macros(strip_comments(defs))
    assert macros["K"].params == ["n"] and macros["K"].line == 1
    assert _expand(defs, "K(k1)") == "__global__ void k1() { }"


def test_scan_finds_macro_defined_kernels():
    ks = {k.name: k for k in scan(FIX / "kernels.cu")}
    assert sorted(ks) == ["marked_add", "opened_relu", "plain_copy", "scale_f32", "scale_f64"]
    s32, s64 = ks["scale_f32"], ks["scale_f64"]
    assert s32.generated_by == s64.generated_by == "FOR_FLOAT_TYPES(DEFINE_SCALE)"
    assert s32.line == s64.line == 14
    assert [(p.name, p.kind, p.dtype) for p in s64.params] == [
        ("x", "inout", "float64"), ("s", "scalar", "float64"), ("n", "scalar", "int32")]
    assert s32.source.startswith("// generated by FOR_FLOAT_TYPES(DEFINE_SCALE)")
    assert "__global__ void scale_f32(float* x" in s32.source
    assert [(c.grid, c.block) for c in s32.launches] == [("4", "256")]
    assert "grid_stride_loop" in s32.features  # seen through KERNEL_LOOP

    add = ks["marked_add"]
    assert add.launch_bounds == "128" and add.generated_by == ""
    assert [p.kind for p in add.params] == ["input", "input", "output", "scalar"]
    assert "grid_stride_loop" in add.features

    relu = ks["opened_relu"]
    assert relu.extern_c and relu.generated_by == "C_KERNEL(opened_relu)"
    assert (relu.line, relu.end_line) == (28, 30)
    assert [p.kind for p in relu.params] == ["input", "output", "scalar"]


def test_define_bodies_are_not_kernels(tmp_path):
    (tmp_path / "k.cu").write_text("#define UNUSED(n) __global__ void n(float* x) { x[0] = 1; }\n"
                                   "__global__ void real(float* x) { x[0] = 2; }\n")
    assert [k.name for k in scan(tmp_path / "k.cu")] == ["real"]


def test_slicer_keeps_macro_kernels_and_drops_macro_host_code():
    src = device_source(FIX / "kernels.cu")
    for kept in ("FOR_FLOAT_TYPES(DEFINE_SCALE)", "#define DECLARE_HOST_HELPER", "KERNEL void marked_add",
                 "C_KERNEL(opened_relu)(const float* x"):
        assert kept in src, kept
    for dropped in ("DECLARE_HOST_HELPER(counter)", "int main(", "cudaMalloc"):
        assert dropped not in src, dropped


@needs_cuda
def test_sliced_macro_fixture_compiles_with_nvrtc():
    import cupy as cp

    from kernelport.harness.run_cuda import NVRTC_OPTIONS, NVRTC_PRELUDE

    names = ["scale_f32", "scale_f64", "marked_add", "opened_relu", "plain_copy"]
    mod = cp.RawModule(code=NVRTC_PRELUDE + device_source(FIX / "kernels.cu"), options=NVRTC_OPTIONS,
                       name_expressions=names)
    for n in names:
        mod.get_function(n)


@needs_cuda
def test_macro_kernel_validates_end_to_end(tmp_path):
    from kernelport import tools

    repo = tmp_path / "repo"
    (repo / ".git").mkdir(parents=True)
    shutil.copy(FIX / "kernels.cu", repo / "kernels.cu")
    res = tools.scan_kernels(".", root=str(repo))
    assert res["ok"] and "scale_f64" in res["summary"]
    rk = tools.read_kernel("scale_f64", root=str(repo))
    assert rk["ok"] and "__global__ void scale_f64(double* x" in rk["source"]
    spec = {
        "name": "scale_f64", "source": "kernels.cu", "entry": "scale_f64", "dtypes": ["float64"],
        "params": [{"name": "x", "kind": "inout", "dtype": "float64", "shape": ["n"]},
                   {"name": "s", "kind": "scalar", "dtype": "float64", "value": "s"},
                   {"name": "n", "kind": "scalar", "dtype": "int32", "value": "n"}],
        "launch": {"grid": ["cdiv(n, 256)"], "block": [256], "shared_mem": 0},
        "cases": [{"name": "tiny_7", "dims": {"n": 7, "s": -1.5}},
                  {"name": "odd_4097", "dims": {"n": 4097, "s": 2.5}}],
        "init": {"x": {"dist": "normal", "edges": True}},
    }
    ref = "def reference(x, s, n):\n    return {'x': x * s}\n"
    assert tools.write_reference("scale_f64", ref, spec=json.loads(json.dumps(spec)), root=str(repo))["ok"]
    val = tools.validate_reference("scale_f64", root=str(repo))
    assert val["status"] == "PASS", val
